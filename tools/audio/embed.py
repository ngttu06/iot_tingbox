#!/usr/bin/env python3
"""Reproducibly embed checked-in MP3 clips in firmware, verifying manifest hashes."""
import hashlib
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
ASSETS = ROOT/'firmware/assets/audio'
DEST = ROOT/'firmware/SmartPayESP32'
manifest = json.loads((ASSETS/'manifest.json').read_text())
header = '''// Generated by tools/audio/embed.py. Do not edit.
#pragma once
#include <Arduino.h>
struct AudioClip { const char* id; const unsigned char* data; size_t size; };
const AudioClip* findAudioClip(const char* id);
extern const size_t AUDIO_CLIP_COUNT;
'''
body = ['// Generated by tools/audio/embed.py. Do not edit.', '#include "AudioAssets.h"', '#include <cstring>']
entries = []
for clip in manifest['clips']:
    name = clip['id']
    data = (ASSETS/clip['file']).read_bytes()
    if len(data) != clip['bytes'] or hashlib.sha256(data).hexdigest() != clip['sha256']:
        raise SystemExit(f'Asset mismatch: {name}')
    body.append(f'static const unsigned char clip_{name}[] PROGMEM = {{')
    body += ['  '+','.join(f'0x{x:02x}' for x in data[i:i+24])+',' for i in range(0,len(data),24)]
    body.append('};')
    entries.append(f'  {{"{name}",clip_{name},sizeof(clip_{name})}},')
body += ['static const AudioClip clips[] = {', *entries, '};',
         'const size_t AUDIO_CLIP_COUNT = sizeof(clips)/sizeof(clips[0]);',
         'const AudioClip* findAudioClip(const char* id) {',
         '  for (size_t i=0;i<AUDIO_CLIP_COUNT;i++) if (!strcmp(clips[i].id,id)) return &clips[i];',
         '  return nullptr;', '}']
DEST.mkdir(parents=True, exist_ok=True)
(DEST/'AudioAssets.h').write_text(header)
(DEST/'AudioAssets.cpp').write_text('\n'.join(body)+'\n')
print(f'Embedded {len(entries)} audio clips')