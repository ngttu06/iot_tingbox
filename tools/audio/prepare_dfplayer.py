#!/usr/bin/env python3
"""Prepare a local SD-card payload. Never format or write removable drives."""
import argparse
import hashlib
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
# Stable numbering, independent of manifest order. Append, never reorder.
TRACKS = (
    'chao_mung', 'ket_noi_wifi', 'cam_on', 'da_nhan_duoc',
    'khong', 'mot', 'hai', 'ba', 'bon', 'nam', 'sau', 'bay', 'tam', 'chin',
    'muoi', 'muoi_hang_chuc', 'tram', 'nghin', 'trieu', 'ty', 'linh',
    'mot_sau_muoi', 'lam', 'viet_nam_dong',
)
HEADER = ROOT / 'firmware/SmartPayESP32/DfPlayerTracks.h'


def generate_header():
    rows = '\n'.join(f'  {{"{name}",{number}}},' for number, name in enumerate(TRACKS, 1))
    return (
        '// Generated by tools/audio/prepare_dfplayer.py; stable SD track IDs.\n'
        '#pragma once\n#include <cstdint>\n#include <cstring>\n\n'
        'struct DfPlayerTrack {const char* id;uint16_t number;};\n'
        'static const DfPlayerTrack DFPLAYER_TRACKS[]={\n' + rows + '\n};\n'
        'inline uint16_t findDfPlayerTrack(const char* id){\n'
        '  if(id)for(const auto& track:DFPLAYER_TRACKS)\n'
        '    if(!std::strcmp(id,track.id))return track.number;\n'
        '  return 0;\n}\n'
    )


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check', action='store_true', help='Check mapping/assets without writing files')
    args = parser.parse_args()
    assets = ROOT / 'firmware/assets/audio'
    manifest = json.loads((assets / 'manifest.json').read_text(encoding='utf-8'))
    clips = {clip['id']: clip for clip in manifest['clips']}
    if len(clips) != len(manifest['clips']) or set(clips) != set(TRACKS):
        raise ValueError('Manifest IDs must match the stable DFPlayer map exactly')
    payload = []
    for number, name in enumerate(TRACKS, 1):
        clip = clips[name]
        data = (assets / clip['file']).read_bytes()
        if len(data) != clip['bytes'] or hashlib.sha256(data).hexdigest() != clip['sha256']:
            raise ValueError(f'Invalid audio asset: {name}')
        payload.append((f'{number:04}.mp3', name, data))
    expected = generate_header()
    if args.check:
        if not HEADER.exists() or HEADER.read_text(encoding='utf-8') != expected:
            raise ValueError('DFPlayerTracks.h is stale; run prepare_dfplayer.py')
        print(f'PASS: {len(payload)} DFPlayer track IDs and MP3 hashes')
        return
    HEADER.write_text(expected, encoding='utf-8', newline='\n')
    output = ROOT / '.tools/dfplayer-sd'
    folder = output / 'mp3'
    folder.mkdir(parents=True, exist_ok=True)
    for filename, _, data in payload:
        (folder / filename).write_bytes(data)
    mapping = '\n'.join(f'mp3/{filename}\t{name}' for filename, name, _ in payload)
    (output / 'track-map.txt').write_text(mapping + '\n', encoding='utf-8')
    print(f'Prepared {len(payload)} verified MP3 files in {folder}')
    print('Copy the mp3 directory to a FAT16/FAT32 microSD root; no card was modified.')


if __name__ == '__main__':
    main()